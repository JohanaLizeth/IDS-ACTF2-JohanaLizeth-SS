import numpy as np
import matplotlib.pyplot as plt

# 1. CONFIGURACIÓN DEL TIEMPO
Fs = 1000          # Frecuencia de muestreo (1000 puntos por segundo)
T = 1.0 / Fs       # Tiempo entre cada punto muestreado
t = np.arange(-1.0, 1.0, T)  # Vector de tiempo de -1 a 1 segundo
N = len(t)         # Cantidad total de puntos medidos

# 2. DEFINICIÓN DE SEÑAL LENTA Y SEÑAL ACELERADA (ESCALADA)
# Señal Original: Onda senoidal que vibra a 10 Hz (Normal)
f0 = 10
senal_normal = np.sin(2 * np.pi * f0 * t)

# Señal Escalada: Modificamos el argumento para que vaya el DOBLE de rápido (20 Hz)
# Esto equivale matemáticamente a comprimir el tiempo a la mitad: x(2t)
senal_rapida = np.sin(2 * np.pi * (2 * f0) * t)

# 3. CÁLCULO DE LA TRANSFORMADA DE FOURIER (FFT)
fft_normal = np.fft.fftshift(np.fft.fft(senal_normal)) / N
fft_rapida = np.fft.fftshift(np.fft.fft(senal_rapida)) / N

# Extraemos las magnitudes
mag_normal = np.abs(fft_normal)
mag_rapida = np.abs(fft_rapida)

# Creamos las etiquetas del eje de frecuencias
frecuencias = np.fft.fftshift(np.fft.fftfreq(N, T))

# 4. GRAFICACIÓN DE LOS RESULTADOS
plt.figure(figsize=(14, 5))

# Gráfica 1: Comparación en el dominio del Tiempo
plt.subplot(1, 2, 1)
plt.plot(t, senal_normal, color='blue', label='Normal (10 Hz)')
plt.plot(t, senal_rapida, color='purple', linestyle='--', label='Acelerada al Doble (20 Hz)')
plt.xlim(-0.2, 0.2) # Zoom para ver los ciclos claramente
plt.title('Comparación en el Dominio del Tiempo')
plt.xlabel('Tiempo (s)')
plt.ylabel('Amplitud')
plt.legend()
plt.grid(True)

# Gráfica 2: Comparación en el dominio de la Frecuencia
plt.subplot(1, 2, 2)
plt.plot(frecuencias, mag_normal, color='blue', label='Espectro Normal (Picos en ±10 Hz)')
plt.plot(frecuencias, mag_rapida, color='purple', linestyle='--', label='Espectro Expandido (Picos en ±20 Hz)')
plt.xlim(-30, 30) # Zoom para observar la posición de los picos
plt.title('Efecto del Escalamiento en la Frecuencia')
plt.xlabel('Frecuencia (Hz)')
plt.ylabel('Magnitud')
plt.legend()
plt.grid(True)

plt.tight_layout()
plt.show()