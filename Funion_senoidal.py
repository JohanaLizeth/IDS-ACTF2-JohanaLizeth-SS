import numpy as np
import matplotlib.pyplot as plt

# 1. CONFIGURACIÓN DEL TIEMPO
Fs = 1000          # Frecuencia de muestreo (1000 puntos por segundo)
T = 1.0 / Fs       # Tiempo entre cada punto muestreado
t = np.arange(-1.0, 1.0, T)  # Vector de tiempo de -1 a 1 segundo
N = len(t)         # Cantidad total de puntos medidos

# 2. DEFINICIÓN DE LA ONDA SENOIDAL
# Definimos una frecuencia de 10 Hz (la señal completará 10 ciclos por segundo)
f0 = 10
senoidal = np.sin(2 * np.pi * f0 * t)

# 3. CÁLCULO DE LA TRANSFORMADA DE FOURIER (FFT)
fft_resultado = np.fft.fft(senoidal)           # Calculamos la FFT
fft_centrada = np.fft.fftshift(fft_resultado)  # Centramos el cero en el medio
magnitud = np.abs(fft_centrada) / N            # Obtenemos el tamaño del espectro

# Creamos las etiquetas del eje de frecuencias
frecuencias = np.fft.fftshift(np.fft.fftfreq(N, T))

# 4. GRAFICACIÓN DE LOS RESULTADOS
plt.figure(figsize=(12, 5))

# Gráfica en el Dominio del Tiempo
plt.subplot(1, 2, 1)
plt.plot(t, senoidal, color='blue', linewidth=2)
plt.xlim(-0.3, 0.3) # Hacemos un zoom temporal para poder ver los ciclos claramente
plt.title('Onda Senoidal (Dominio del Tiempo)')
plt.xlabel('Tiempo (segundos)')
plt.ylabel('Amplitud')
plt.grid(True)

# Gráfica en el Dominio de la Frecuencia
plt.subplot(1, 2, 2)
plt.plot(frecuencias, magnitud, color='red', linewidth=2)
plt.xlim(-20, 20) # Zoom alrededor de las frecuencias bajas para ver los picos
plt.title('Espectro de Magnitud - Impulsos Puros')
plt.xlabel('Frecuencia (Hz)')
plt.ylabel('Magnitud')
plt.grid(True)

plt.tight_layout()
plt.show()