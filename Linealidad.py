import numpy as np
import matplotlib.pyplot as plt

# 1. CONFIGURACIÓN DEL TIEMPO
Fs = 1000          # Frecuencia de muestreo (1000 puntos por segundo)
T = 1.0 / Fs       # Tiempo entre cada punto muestreado
t = np.arange(-1.0, 1.0, T)  # Vector de tiempo de -1 a 1 segundo
N = len(t)         # Cantidad total de puntos medidos

# 2. DEFINICIÓN DE DOS SEÑALES DISTINTAS
# Señal A: Onda senoidal pura de 10 Hz
f_A = 10
senal_A = np.sin(2 * np.pi * f_A * t)

# Señal B: Onda senoidal pura de 30 Hz
f_B = 30
senal_B = np.sin(2 * np.pi * f_B * t)

# SEÑAL COMBINADA (Sumamos ambas señales)
senal_mezclada = senal_A + senal_B

# 3. CÁLCULO DE LA TRANSFORMADA DE FOURIER (FFT)
fft_A = np.fft.fftshift(np.fft.fft(senal_A)) / N
fft_B = np.fft.fftshift(np.fft.fft(senal_B)) / N
fft_mezclada = np.fft.fftshift(np.fft.fft(senal_mezclada)) / N

# Extraemos las magnitudes individuales y la de la mezcla
mag_A = np.abs(fft_A)
mag_B = np.fft.fftshift(np.abs(np.fft.fft(senal_B))) / N # Magnitud de B
mag_mezclada = np.abs(fft_mezclada)

# Creamos las etiquetas del eje de frecuencias
frecuencias = np.fft.fftshift(np.fft.fftfreq(N, T))

# 4. GRAFICACIÓN DE LOS RESULTADOS
plt.figure(figsize=(14, 5))

# Gráfica 1: Señales en el tiempo (Se observa la combinación de ondas)
plt.subplot(1, 2, 1)
plt.plot(t, senal_mezclada, color='blue', lw=2)
plt.xlim(-0.2, 0.2) # Zoom para apreciar la deformación de la onda por la suma
plt.title('Señal Mezclada (Señal A + Señal B) - Tiempo')
plt.xlabel('Tiempo (s)')
plt.ylabel('Amplitud')
plt.grid(True)

# Gráfica 2: Espectro en Frecuencia (Muestra la superposición exacta)
plt.subplot(1, 2, 2)
plt.plot(frecuencias, mag_mezclada, color='red', lw=2)
plt.xlim(-40, 40) # Zoom en las frecuencias de interés (10 Hz y 30 Hz)
plt.title('Espectro de la Mezcla (Linealidad Comprobada) - Frecuencia')
plt.xlabel('Frecuencia (Hz)')
plt.ylabel('Magnitud')
plt.grid(True)

plt.tight_layout()
plt.show()