import numpy as np
import matplotlib.pyplot as plt

# 1. CONFIGURACIÓN DEL TIEMPO
Fs = 1000          # Frecuencia de muestreo (1000 puntos por segundo)
T = 1.0 / Fs       # Tiempo entre cada punto muestreado
t = np.arange(-1.0, 1.0, T)  # Vector de tiempo de -1 a 1 segundo
N = len(t)         # Cantidad total de puntos medidos

# 2. DEFINICIÓN DE SEÑAL ORIGINAL Y SEÑAL DESPLAZADA (RETRASADA)
# Señal original: Pulso rectangular centrado en el cero
pulso_original = np.where(np.abs(t) <= 0.1, 1.0, 0.0)

# Señal desplazada: El mismo pulso pero retrasado t0 = 0.25 segundos hacia la derecha
t0 = 0.25
pulso_desplazado = np.where(np.abs(t - t0) <= 0.1, 1.0, 0.0)

# 3. CÁLCULO DE LA TRANSFORMADA DE FOURIER (FFT)
fft_orig = np.fft.fftshift(np.fft.fft(pulso_original)) / N
fft_desp = np.fft.fftshift(np.fft.fft(pulso_desplazado)) / N

# Extraemos la magnitud de ambas señales
mag_original = np.abs(fft_orig)
mag_desplazada = np.abs(fft_desp)

# Extraemos la fase (en radianes) de ambas señales
fase_original = np.angle(fft_orig)
fase_desplazada = np.angle(fft_desp)

# Limpieza numérica de fase para que no se vea distorsionada por el ruido matemático
fase_original[mag_original < 1e-4] = 0.0
fase_desplazada[mag_desplazada < 1e-4] = 0.0

# Creamos las etiquetas del eje de frecuencias
frecuencias = np.fft.fftshift(np.fft.fftfreq(N, T))

# 4. GRAFICACIÓN DE LOS RESULTADOS
plt.figure(figsize=(14, 8))

# Gráfica 1: Comparación en el Tiempo
plt.subplot(2, 2, 1)
plt.plot(t, pulso_original, color='blue', label='Original (Centrado)')
plt.plot(t, pulso_desplazado, color='orange', linestyle='--', label='Desplazado (t=0.25s)')
plt.title('Señales en el Dominio del Tiempo')
plt.xlabel('Tiempo (s)')
plt.ylabel('Amplitud')
plt.legend()
plt.grid(True)

# Gráfica 2: Comparación de Magnitudes (Frecuencia)
plt.subplot(2, 2, 2)
plt.plot(frecuencias, mag_original, color='red', label='Magnitud Original')
plt.plot(frecuencias, mag_desplazada, color='black', linestyle=':', label='Magnitud Desplazada')
plt.xlim(-20, 20)
plt.title('Espectros de Magnitud (Idénticos)')
plt.xlabel('Frecuencia (Hz)')
plt.ylabel('Magnitud')
plt.legend()
plt.grid(True)

# Gráfica 3: Fase Original
plt.subplot(2, 2, 3)
plt.plot(frecuencias, fase_original, color='green')
plt.xlim(-10, 10)
plt.title('Fase Original (Sin desplazamiento)')
plt.xlabel('Frecuencia (Hz)')
plt.ylabel('Fase (Rad)')
plt.grid(True)

# Gráfica 4: Fase Desplazada
plt.subplot(2, 2, 4)
plt.plot(frecuencias, fase_desplazada, color='magenta')
plt.xlim(-10, 10)
plt.title('Fase Desplazada (Cambio Lineal / Pendiente)')
plt.xlabel('Frecuencia (Hz)')
plt.ylabel('Fase (Rad)')
plt.grid(True)

plt.tight_layout()
plt.show()